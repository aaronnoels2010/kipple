//! Compiles `locales/<lang>/tray.json` into the crate (ADR-0004): the tray menu and OS
//! notifications must work without a webview. Fails the build if a language misses a key.
//! Also generates a `key::*` constant per key, so a typo in Rust code fails to compile.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write;
use std::path::Path;

fn main() {
    let locales = Path::new(&env::var("CARGO_MANIFEST_DIR").unwrap()).join("../../locales");
    println!("cargo:rerun-if-changed={}", locales.display());

    let mut catalogs: BTreeMap<String, BTreeMap<String, String>> = BTreeMap::new();
    for entry in std::fs::read_dir(&locales).expect("locales/ missing") {
        let dir = entry.unwrap().path();
        let file = dir.join("tray.json");
        if !file.is_file() {
            continue;
        }
        println!("cargo:rerun-if-changed={}", file.display());
        let text = std::fs::read_to_string(&file).unwrap();
        let messages: BTreeMap<String, String> =
            serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", file.display()));
        catalogs.insert(
            dir.file_name().unwrap().to_string_lossy().into_owned(),
            messages,
        );
    }

    let source = catalogs
        .get("en")
        .expect("locales/en/tray.json is the source language");
    for (lang, messages) in &catalogs {
        let missing: Vec<_> = source
            .keys()
            .filter(|k| !messages.contains_key(*k))
            .collect();
        let extra: Vec<_> = messages
            .keys()
            .filter(|k| !source.contains_key(*k))
            .collect();
        assert!(
            missing.is_empty() && extra.is_empty(),
            "locales/{lang}/tray.json: missing {missing:?}, unknown {extra:?}"
        );
    }

    let mut out = String::from("// Generated by build.rs from locales/*/tray.json.\n");
    out.push_str("pub(crate) const MESSAGES: &[(&str, &str, &str)] = &[\n");
    for (lang, messages) in &catalogs {
        for (key, message) in messages {
            writeln!(out, "    ({lang:?}, {key:?}, {message:?}),").unwrap();
        }
    }
    out.push_str("];\n\n/// Every tray message key, e.g. `key::TRAY_FILES_TIDIED` for `tray.filesTidied`.\npub mod key {\n");
    for key in source.keys() {
        writeln!(out, "    pub const {}: &str = {key:?};", constant_name(key)).unwrap();
    }
    out.push_str("}\n");
    #[expect(
        clippy::disallowed_methods,
        reason = "generated code goes to OUT_DIR, never to user files (ADR-0002)"
    )]
    std::fs::write(
        Path::new(&env::var("OUT_DIR").unwrap()).join("catalog.rs"),
        out,
    )
    .unwrap();
}

/// `tray.filesTidied` → `TRAY_FILES_TIDIED`.
fn constant_name(key: &str) -> String {
    let mut name = String::new();
    for ch in key.chars() {
        match ch {
            '.' => name.push('_'),
            c if c.is_ascii_uppercase() => {
                name.push('_');
                name.push(c);
            }
            c => name.push(c.to_ascii_uppercase()),
        }
    }
    name
}
