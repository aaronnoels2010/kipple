//! Single source of truth for the forbidden APIs that enforce ADR-0002 (only the Executor
//! mutates files) and the purity of kipple-core. Both clippy.toml files are GENERATED from the
//! lists below: `cargo xtask clippy-config --write`; CI runs the check mode.

/// A forbidden API. `os_specific` paths don't resolve on every OS, so clippy must not reject them.
pub struct Ban {
    pub path: &'static str,
    pub os_specific: bool,
}

const fn any(path: &'static str) -> Ban {
    Ban {
        path,
        os_specific: false,
    }
}

const fn os(path: &'static str) -> Ban {
    Ban {
        path,
        os_specific: true,
    }
}

/// File-mutating APIs: forbidden in every crate. Only the Executor and the platform adapters it
/// calls get a per-module `#[allow(clippy::disallowed_methods)]`.
pub const FILE_MUTATING: &[Ban] = &[
    any("std::fs::rename"),
    any("std::fs::remove_file"),
    any("std::fs::remove_dir"),
    any("std::fs::remove_dir_all"),
    any("std::fs::write"),
    any("std::fs::copy"),
    any("std::fs::create_dir"),
    any("std::fs::create_dir_all"),
    any("std::fs::DirBuilder::create"),
    any("std::fs::hard_link"),
    any("std::fs::set_permissions"),
    any("std::fs::File::create"),
    any("std::fs::File::create_new"),
    any("std::fs::File::set_len"),
    any("std::fs::File::set_permissions"),
    any("std::fs::File::set_times"),
    any("std::fs::File::set_modified"),
    any("std::fs::OpenOptions::write"),
    any("std::fs::OpenOptions::append"),
    any("std::fs::OpenOptions::truncate"),
    any("std::fs::OpenOptions::create"),
    any("std::fs::OpenOptions::create_new"),
    os("std::os::unix::fs::symlink"),
    os("std::os::unix::fs::chown"),
    os("std::os::unix::fs::lchown"),
    os("std::os::windows::fs::symlink_file"),
    os("std::os::windows::fs::symlink_dir"),
];

/// Every other kind of I/O: additionally forbidden in kipple-core, which must stay pure.
pub const CORE_IO: &[Ban] = &[
    any("std::fs::read"),
    any("std::fs::read_to_string"),
    any("std::fs::read_dir"),
    any("std::fs::metadata"),
    any("std::fs::symlink_metadata"),
    any("std::fs::canonicalize"),
    any("std::fs::OpenOptions::open"),
    any("std::env::args"),
    any("std::env::var"),
    any("std::env::var_os"),
    any("std::env::vars"),
    any("std::env::current_dir"),
    any("std::io::stdin"),
    any("std::io::stdout"),
    any("std::io::stderr"),
    any("std::net::TcpStream::connect"),
    any("std::net::TcpListener::bind"),
    any("std::net::UdpSocket::bind"),
    any("std::time::SystemTime::now"),
    any("std::time::Instant::now"),
    any("std::thread::spawn"),
];

/// Types forbidden in kipple-core (this also covers all their methods, e.g. `File::open`).
pub const CORE_TYPES: &[Ban] = &[
    any("std::fs::File"),
    any("std::net::TcpStream"),
    any("std::process::Command"),
];

const MUTATING_REASON: &str =
    "ADR-0002: only the Executor (and the adapters it calls) may change files";
const CORE_REASON: &str =
    "kipple-core is pure: no I/O, environment, network, threads or clock; pass data in";

fn entries(out: &mut String, bans: &[Ban], reason: &str) {
    for ban in bans {
        let invalid = if ban.os_specific {
            ", allow-invalid = true"
        } else {
            ""
        };
        out.push_str(&format!(
            "  {{ path = \"{}\", reason = \"{reason}\"{invalid} }},\n",
            ban.path
        ));
    }
}

const GENERATED: &str = "# GENERATED by `cargo xtask clippy-config --write` from xtask/src/clippy_config.rs. Do not edit.\n";

/// The root clippy.toml (all crates except kipple-core).
pub fn render_root() -> String {
    let mut s = String::from(GENERATED);
    s.push_str("# crates/kipple-core/clippy.toml REPLACES this file for kipple-core (clippy has no `extends`).\n\n");
    s.push_str("disallowed-methods = [\n");
    entries(&mut s, FILE_MUTATING, MUTATING_REASON);
    s.push_str("]\n");
    s
}

/// crates/kipple-core/clippy.toml: the mutation list again, plus every other kind of I/O.
pub fn render_core() -> String {
    let mut s = String::from(GENERATED);
    s.push_str("\ndisallowed-methods = [\n");
    entries(&mut s, FILE_MUTATING, MUTATING_REASON);
    entries(&mut s, CORE_IO, CORE_REASON);
    s.push_str("]\n\ndisallowed-types = [\n");
    entries(&mut s, CORE_TYPES, CORE_REASON);
    s.push_str("]\n");
    s
}

/// The generated files, as (path relative to the repo root, expected content).
pub fn files() -> [(&'static str, String); 2] {
    [
        ("clippy.toml", render_root()),
        ("crates/kipple-core/clippy.toml", render_core()),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    fn paths(toml: &str) -> Vec<&str> {
        toml.lines()
            .filter_map(|l| l.trim().strip_prefix("{ path = \""))
            .filter_map(|l| l.split('"').next())
            .collect()
    }

    #[test]
    fn mutating_list_covers_the_dangerous_calls() {
        for api in [
            "std::fs::rename",
            "std::fs::remove_file",
            "std::fs::remove_dir_all",
            "std::fs::write",
            "std::fs::DirBuilder::create",
        ] {
            assert!(
                FILE_MUTATING.iter().any(|b| b.path == api),
                "{api} must be forbidden"
            );
        }
    }

    #[test]
    fn root_forbids_mutation_only() {
        let root = render_root();
        let p = paths(&root);
        assert_eq!(p.len(), FILE_MUTATING.len());
        assert!(p.contains(&"std::fs::rename") && !p.contains(&"std::fs::read_dir"));
    }

    #[test]
    fn core_repeats_mutation_and_adds_all_io() {
        let core = render_core();
        let p = paths(&core);
        assert_eq!(
            p.len(),
            FILE_MUTATING.len() + CORE_IO.len() + CORE_TYPES.len()
        );
        for api in [
            "std::fs::rename",
            "std::fs::read_dir",
            "std::env::var",
            "std::time::SystemTime::now",
            "std::fs::File",
        ] {
            assert!(p.contains(&api), "{api} must be forbidden in core");
        }
    }

    #[test]
    fn os_specific_paths_may_be_unresolvable() {
        let root = render_root();
        let symlink = root
            .lines()
            .find(|l| l.contains("\"std::os::unix::fs::symlink\""))
            .unwrap();
        assert!(symlink.contains("allow-invalid = true"));
        let rename = root
            .lines()
            .find(|l| l.contains("\"std::fs::rename\""))
            .unwrap();
        assert!(!rename.contains("allow-invalid"));
    }

    #[test]
    fn every_path_is_listed_once() {
        for toml in [render_root(), render_core()] {
            let mut p = paths(&toml);
            let n = p.len();
            p.sort();
            p.dedup();
            assert_eq!(p.len(), n, "duplicate entries");
        }
    }
}
